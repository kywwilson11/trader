_nonfinite_p_warned = False


def _calibrated(calib, raw: np.ndarray) -> np.ndarray:
    global _calib_fallback_warned
    try:
        return np.clip(calib.predict(raw), 0.0, 1.0)
    except Exception as e:
        if not _calib_fallback_warned:
            _calib_fallback_warned = True
            print(f"[META] calibrator predict failed ({e}) — serving raw scores")
        return np.clip(raw, 0.0, 1.0)


def meta_probability_live(prefix: str, snapshot: dict, pred: float) -> float | None:
    """Calibrated P(trade profits net of costs) for a live candidate.

    Returns None when no meta model exists — the layer is strictly
    optional and absent models leave behavior unchanged.
    """
    global _nonfinite_p_warned
    loaded = _load(prefix)
    if loaded is None:
        return None
    booster, calib = loaded
    x = features_from_snapshot(snapshot, pred).reshape(1, -1)
    raw = booster.predict(x)
    p = float(_calibrated(calib, np.asarray(raw))[0])
    if not np.isfinite(p):
        # calibration.py's contract: "predict propagates non-finite raw as
        # NaN — callers must guard." Unguarded, base_loop's veto (NaN < x is
        # False) passes AND its tilt clamp max(0.1, min(TILT_MAX, nan))
        # resolves to TILT_MAX — the MAXIMUM boost. Serve the documented
        # neutral (None) instead.
        if not _nonfinite_p_warned:
            _nonfinite_p_warned = True
            print("[META] non-finite calibrated probability — served as None "
                  "(neutral)")
        return None
    return p


def predict_meta_array(prefix: str, tdf, preds) -> np.ndarray | None:
    """Per-bar meta probabilities for the backtester (policy parity)."""
    loaded = _load(prefix)
    if loaded is None:
        return None
    booster, calib = loaded
    try:
        mat = build_feature_matrix(tdf, preds)
        raw = booster.predict(mat)
        return _calibrated(calib, np.asarray(raw))
    except Exception as e:
        # backtest.py wraps this call in a bare `except Exception: pass` —
        # emit the reason HERE so a present-but-broken meta layer cannot
        # silently turn the promotion gate's veto into a no-op.
        print(f"[META] scoring failed ({e}) — meta gate disabled for this frame")
        return None


def meta_size_mult(p: float | None) -> float:
    """Bounded sizing multiplier from the calibrated probability.

    Non-finite p is treated as None -> neutral 1.0: np.clip propagates NaN,
    and base_loop's max(0.1, min(TILT_MAX, tilt)) resolves a NaN tilt to
    TILT_MAX (the maximum boost), so this guard is load-bearing.
    """
    if p is None or not np.isfinite(p):
        return 1.0
    return float(np.clip(2.0 * p, 0.6, 1.3))


