def _calib_slice_guard(raw_val, y_slice) -> str | None:
    """Pre-fit guards for ANY calibration sample (mirror of fit_calibrator's
    degenerate guards, applied to the legacy same-slice branch — D13a).
    Returns a refusal reason or None."""
    raw_val = np.asarray(raw_val, float)
    y_slice = np.asarray(y_slice, float)
    if raw_val.size < META_GUARD_MIN_CALIB_N:
        return f'calib_slice_too_thin(n={raw_val.size})'
    if np.unique(y_slice).size < 2:
        return 'calib_slice_one_class'
    if np.unique(raw_val).size < 2:
        return 'calib_slice_constant_scores'
    return None


def _publish_guard_reasons(p_all, val_auc, frac_veto) -> list[str]:
    """Post-fit refusal reasons on the calibrated-p distribution + skill.
    A constant p=0.0 vetoes the whole book; ~1.0 boosts everything (D13a)."""
    reasons = []
    p_all = np.asarray(p_all, float)
    if float(np.max(p_all) - np.min(p_all)) < META_GUARD_MIN_P_RANGE:
        reasons.append(f'constant_calibrated_p(range<{META_GUARD_MIN_P_RANGE})')
    if frac_veto >= META_GUARD_MAX_FRAC_VETO:
        reasons.append(f'frac_below_veto={frac_veto:.2f}>={META_GUARD_MAX_FRAC_VETO}')
    if val_auc is not None and val_auc < META_GUARD_MIN_VAL_AUC:
        reasons.append(f'val_auc={val_auc:.3f}<{META_GUARD_MIN_VAL_AUC}')
    return reasons


