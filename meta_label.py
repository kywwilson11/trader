def _hour_encode(hour: float) -> tuple[float, float]:
    ang = 2 * math.pi * hour / 24.0
    return math.sin(ang), math.cos(ang)


def build_feature_matrix(tdf, preds) -> np.ndarray:
    """Per-bar meta features from a harvest-style DataFrame (training)."""
    n = len(tdf)
    preds = np.asarray(preds, dtype=np.float64)
    if preds.shape != (n,):
        raise ValueError(f'build_feature_matrix: preds shape {preds.shape} '
                         f'!= len(tdf) {n}')
    # Single hour pass feeding both trig columns — vectorized twin of
    # _hour_encode (the live scalar path); keep the two in sync.
    hours = (tdf.index.hour.to_numpy(dtype=np.float64)
             if hasattr(tdf.index, 'hour')
             else np.array([t.hour for t in tdf.index], dtype=np.float64))
    hour_ang = 2 * np.pi * hours / 24.0
    cols = {}
    for name in META_FEATURES:
        if name == 'pred':
            cols[name] = preds
        elif name == 'hour_sin':
            cols['hour_sin'] = np.sin(hour_ang)
        elif name == 'hour_cos':
            cols['hour_cos'] = np.cos(hour_ang)
        elif name in tdf.columns:
            cols[name] = tdf[name].values.astype(np.float64)
        else:
            cols[name] = np.zeros(n, dtype=np.float64)
    mat = np.column_stack([cols[name] for name in META_FEATURES])
    return np.nan_to_num(mat, nan=0.0, posinf=0.0, neginf=0.0)


def features_from_snapshot(snapshot: dict, pred: float,
                           hour: float | None = None) -> np.ndarray:
    """Live feature vector from the loop's indicator snapshot."""
    if hour is None:
        from datetime import datetime, timezone
        hour = datetime.now(timezone.utc).hour
    hs, hc = _hour_encode(hour)
    vals = []
    for name in META_FEATURES:
        if name == 'pred':
            vals.append(float(pred) if pred is not None else 0.0)
        elif name == 'hour_sin':
            vals.append(hs)
        elif name == 'hour_cos':
            vals.append(hc)
        else:
            v = snapshot.get(name)
            try:
                v = float(v)
                if not np.isfinite(v):
                    v = 0.0
            except (TypeError, ValueError):
                v = 0.0
            vals.append(v)
    return np.asarray(vals, dtype=np.float64)


