"""Meta-labeling: a second model that sizes/vetoes the first one's trades.

Lopez de Prado (AFML ch.3): keep the primary model for DIRECTION, then
train a secondary classifier on "did acting on this signal make money net
of costs?" and use its calibrated probability for bet sizing. Replicated
gains (Hudson & Thames): precision 0.48 -> 0.54 on the same primary.

The training set is generated by REPLAYING the primary model's signals
through the exact live exit stack (policy_exits.exit_walk — the same
kernel the backtester and the TB labels use) at a LOWERED entry threshold,
so the meta model sees plenty of marginal trades it should learn to
reject. The final ~12% of rows — a row-quantile approximation of the
hypersearch holdout, recomputed here over the full harvest frame rather
than read from hypersearch (which derives its boundary from a possibly
--max-rows-capped row set) — is excluded from meta training so the
policy-backtest gate stays honest; the resolved cutoff is recorded in
meta_meta.json so drift between the two boundaries is observable.

KNOWN LIMITS (2026-07 panel, owner queue): the replay's entry population
diverges from the deployed policy beyond the deliberate threshold
lowering (no cost/edge floor, no post-hard-stop lockout, no stock entry
windows, no q10 veto — see _gen_meta_rows), and the 'pred' feature is the
primary's IN-SAMPLE fitted value on its own training window (rev-07-01
"meta in-sample-primary leak") — no calibration mode can remove that.
2026-08 R2: META_OOF_PRED (uses persisted walk-forward OOF predictions when
fresh) and META_REPLAY_POLICY_PARITY (applies the live admission conditions
to the replay) address these behind default-OFF flags; meta_meta.json stamps
pred_source and replay-parity diagnostics unconditionally.

Live use (both loops + backtest, for policy parity):
  - p < META_VETO_PROB (0.30): skip the entry
  - otherwise size tilt = clip(2p, 0.6, 1.3)  (p=0.5 -> neutral 1.0x)

Usage:
    python meta_label.py --prefix stock      # train after the primary
    python meta_label.py                     # crypto
    python meta_label.py --no-publish        # write {prefix}meta_*.staged only
    python meta_label.py --promote-staged    # guard-check + promote .staged

Guarded-publish contract (2026-08 R1, D13a/D13b): training now stages the
artifact triple, runs degenerate-calibrator guards, and only then atomically
promotes staged -> live. A refusal leaves the previous consistent live triple
(or the fail-open-neutral absence) untouched and writes {prefix}meta_refused.json.
"""

