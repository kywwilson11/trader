def _gen_meta_rows(tdf, preds, asset_type, threshold, policy, *,
                   entry_preds=None, parity=False, entry_ok=None,
                   q10_preds=None, q10_floor=None, diag=None):
    """Replay the primary's signals through the live exit stack.

    Entries at META_THRESHOLD_FRACTION x the live threshold so the meta
    model also sees the marginal signals it should learn to veto.
    Returns (features, labels, net_returns, entry_times, exit_times).

    `entry_preds` (OOF, META_OOF_PRED) replaces `preds` for ADMISSION and
    the 'pred' feature only — `preds` still drives exit_walk (signal-exit
    inputs are label semantics; changing them is beyond B04.1's binding).

    KNOWN DIVERGENCES from the deployed entry policy (2026-07 panel — the
    threshold relaxation above is the only DELIBERATE one): closed under
    META_REPLAY_POLICY_PARITY (parity=True) — required_edge_pct floor,
    post-hard-stop lockout, stock entry windows (entry_ok), q10 tail veto
    (q10_preds/q10_floor); legacy population when False. Both populations'
    row counts + per-condition first-fail drop counts land in `diag` (dict,
    updated in place) regardless of the flag.
    """
    from policy_exits import exit_walk, eod_mask_from_index, REASON_NAMES
    from fees import round_trip_cost_pct, required_edge_pct

    closes = tdf['Close'].values
    highs = tdf['High'].values if 'High' in tdf.columns else closes
    lows = tdf['Low'].values if 'Low' in tdf.columns else closes
    opens = tdf['Open'].values if 'Open' in tdf.columns else closes
    atr = tdf['ATR'].values if 'ATR' in tdf.columns else np.full(len(closes), np.nan)
    is_eod = eod_mask_from_index(tdf.index, asset_type)

    spread = 0.10 if asset_type == 'crypto' else 0.05
    rt_cost = round_trip_cost_pct(asset_type, spread)
    # Per-bar effective-spread cost when the harvest stamped it (wave 6):
    # removes the train/deploy asymmetry vs the real-spread live gate. Falls
    # back to the flat rt_cost per bar when Eff_Spread_Pct is absent.
    rt_cost_arr = None
    if 'Eff_Spread_Pct' in tdf.columns:
        try:
            from liquidity import per_bar_round_trip_cost, impact_inputs_from_df
            # Optional sqrt market-impact haircut (wave-8 #6), off by default so
            # the meta labels are unchanged unless explicitly enabled + DV30 present.
            adv_arr, impact_notional, impact_k = impact_inputs_from_df(tdf)
            rt_cost_arr = per_bar_round_trip_cost(
                asset_type, tdf['Eff_Spread_Pct'].values,
                adv_dollar=adv_arr, notional=impact_notional, impact_k=impact_k)
        except Exception as e:
            print(f"[META] per-bar spread cost failed ({e}) — flat-cost fallback")
            rt_cost_arr = None
    cooldown_bars = max(1, int(math.ceil(policy['cooldown_min'] / 60)))
    entry_threshold = threshold * META_THRESHOLD_FRACTION
    edge_floor = required_edge_pct(asset_type, spread)   # flat spread —
    # backtest.simulate_ticker convention (live admission uses the real quote)
    hard_stop_code = next(k for k, v in REASON_NAMES.items()
                          if v == 'hard_stop')
    lockout_bars = int(policy['lockout_hours'])   # backtest bar convention

    exit_idx, exit_px, reason_code = exit_walk(
        closes, highs, lows, opens, atr, is_eod, policy,
        preds=preds, threshold=threshold, cooldown_bars=cooldown_bars,
        max_hold=0, use_signal_exit=True)

    # sel drives ADMISSION and the 'pred' FEATURE; preds still drives the
    # exit walk above (signal exits / label semantics unchanged).
    sel = preds if entry_preds is None else np.asarray(entry_preds, float)
    feats_all = build_feature_matrix(tdf, sel)
    n = len(closes)

    def _walk(use_parity):
        """Entry walk over the precomputed exit arrays. use_parity=False is
        the exact legacy population; True mirrors simulate_ticker's
        admission stack with FIRST-FAIL drop counting."""
        pairs = []
        drops = {'lockout': 0, 'edge_floor': 0, 'entry_window': 0, 'q10': 0}
        i = 0
        next_entry_plain = 0    # legacy tracker: plain cooldown only
        next_entry_locked = 0   # parity tracker: hard-stop lockout extension
        while i < n - 1:
            p = sel[i]
            if (np.isnan(p) or i < next_entry_plain or p < entry_threshold
                    or is_eod[i]):
                i += 1
                continue
            if use_parity:
                # Fixed first-fail order for the drop counters
                # (simulate_ticker parity)
                if i < next_entry_locked:
                    drops['lockout'] += 1
                    i += 1
                    continue
                if p < edge_floor:
                    drops['edge_floor'] += 1
                    i += 1
                    continue
                if entry_ok is not None and not entry_ok[i]:
                    drops['entry_window'] += 1
                    i += 1
                    continue
                if (q10_preds is not None and q10_floor is not None
                        and not np.isnan(q10_preds[i])
                        and q10_preds[i] < q10_floor):
                    drops['q10'] += 1
                    i += 1
                    continue
            j = int(exit_idx[i])
            pairs.append((i, j))
            cooldown_after = cooldown_bars
            if use_parity and int(reason_code[i]) == hard_stop_code:
                cooldown_after = max(cooldown_bars, lockout_bars)
            next_entry_plain = j + cooldown_bars
            next_entry_locked = j + cooldown_after
            i = j + 1
        return pairs, drops

    legacy_pairs, _ = _walk(False)
    parity_pairs, drops = _walk(True)
    active_pairs = parity_pairs if parity else legacy_pairs

    rows, labels, nets, times, exit_times = [], [], [], [], []
    for i, j in active_pairs:
        cost_i = rt_cost if rt_cost_arr is None else float(rt_cost_arr[i])
        net = (float(exit_px[i]) - closes[i]) / closes[i] * 100.0 - cost_i
        rows.append(feats_all[i].copy())  # copy: a view would pin the whole per-ticker matrix in RAM
        labels.append(1 if net > 0 else 0)
        nets.append(net)
        times.append(tdf.index[i])
        exit_times.append(tdf.index[j])   # label span end, for the purged calibration
    if isinstance(diag, dict):
        diag.update({
            'rows_legacy': len(legacy_pairs),
            'rows_parity': len(parity_pairs),
            'drops': drops,
            'edge_floor_pct': edge_floor,
            'n_bars': n,
            'n_covered': int(np.isfinite(np.asarray(sel, float)).sum()),
        })
    return rows, labels, nets, times, exit_times


