_loaded: dict[str, tuple] = {}   # prefix -> (artifact stat key, result)


def _stat_key(paths: dict) -> tuple:
    """(model_mtime_ns, calib_mtime_ns); None for a missing file.

    The key changes when artifacts are retrained, deleted (shadow
    promotion), or first appear — so _load self-heals without a restart.
    """
    key = []
    for k in ('model', 'calib'):
        try:
            key.append(os.stat(paths[k]).st_mtime_ns)
        except OSError:
            key.append(None)
    return tuple(key)


def _read_artifacts(paths: dict) -> tuple:
    """Load (booster, calibrator) from disk. Split out so tests can stub it."""
    import joblib
    import lightgbm as lgb
    booster = lgb.Booster(model_file=str(paths['model']))
    calib = joblib.load(paths['calib'])
    return booster, calib


def _check_feature_schema(paths: dict) -> None:
    """WARN (only) when the on-disk manifest's feature list no longer matches
    META_FEATURES. LightGBM matches numpy columns by POSITION, so a
    same-length reorder silently scores the wrong columns with no exception
    anywhere. Enforcement (disabling the layer on drift) is an owner
    decision; this is the tripwire. Missing/unreadable meta.json is silent.
    """
    try:
        if not paths['meta'].exists():
            return
        with open(paths['meta']) as f:
            stored = json.load(f).get('features')
        if stored is not None and list(stored) != list(META_FEATURES):
            print(f"[META] WARNING: feature schema drift — disk={stored} "
                  f"code={META_FEATURES}; served p may be scoring the wrong "
                  f"columns (LightGBM matches by position)")
    except Exception:
        pass


def _load(prefix: str):
    """(booster, calib) for `prefix`, or None when the meta layer is absent.

    Cache contract (2026-07 review P1): keyed on the artifact files'
    mtimes, re-stat'd on every call (two os.stat per candidate — cheap).
    A weekly meta retrain, a shadow promotion that DELETES the champion
    meta files (the gate then fails open to neutral, per shadow.py), or
    the first meta train landing in an already-running bot all take
    effect without a process restart. A load failure is cached as None
    under the same key (no per-bar retry storm) and retried as soon as
    the files change.
    A re-stat after each successful read closes the torn-pair window left
    by the two-file publish (see the publish block).
    """
    paths = _paths(prefix)
    key = _stat_key(paths)
    cached = _loaded.get(prefix)
    if cached is not None and cached[0] == key:
        return cached[1]
    result = None
    if None not in key:
        try:
            result = _read_artifacts(paths)
        except Exception as e:
            print(f"[META] load failed ({e}) — meta layer disabled")
            result = None
        if result is not None:
            # Torn-pair guard (2026-07 panel): the publisher swaps calib and
            # model in two separate os.replace calls and _stat_key wakes on
            # EITHER mtime, so a read landing between the swaps pairs the new
            # calibrator with the old booster. Re-stat after reading; if the
            # key moved, read once more under the new key.
            key2 = _stat_key(paths)
            if key2 != key:
                key = key2
                result = None
                if None not in key2:
                    try:
                        result = _read_artifacts(paths)
                    except Exception as e:
                        print(f"[META] load failed ({e}) — meta layer disabled")
                        result = None
        if result is not None:
            global _calib_fallback_warned, _nonfinite_p_warned
            _calib_fallback_warned = False   # warn-once is per loaded artifact
            _nonfinite_p_warned = False
            _check_feature_schema(paths)
    _loaded[prefix] = (key, result)
    return result


def invalidate_cache():
    global _calib_fallback_warned, _nonfinite_p_warned
    _loaded.clear()
    # Warn-once flags are per artifact generation, not per process (the bots
    # never stop): re-arm them whenever the cache is invalidated.
    _calib_fallback_warned = False
    _nonfinite_p_warned = False


