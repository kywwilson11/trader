OOF_FULL_PARAMS_MIN_ROWS = 1000
OOF_SHRUNK_PARAMS = {'num_leaves': 8, 'max_depth': 3, 'feature_fraction': 0.6}


def oof_pack_from_folds(fold_rows, fold_preds, fold_ids, all_times_s, tickers,
                        ticker_boundaries, holdout_boundary_s) -> dict:
    """Assemble the persistable OOF-prediction pack from per-fold val arrays.

    Pure numpy. `fold_rows`/`fold_preds` are per-fold lists of GLOBAL row
    indices + predictions (hypersearch _train_walk_forward's val slices);
    `all_times_s` is the epoch-SECONDS row-time array (load_data convention);
    `ticker_boundaries` maps name -> (start, end) contiguous global rows.
    Rows past `holdout_boundary_s` are dropped DEFENSIVELY even though
    get_walk_forward_folds already excludes the holdout — the npz must
    NEVER contain holdout-slice predictions.
    """
    if fold_ids is None:
        fold_ids = list(range(len(fold_rows)))
    rows_l, preds_l, fids_l = [], [], []
    for fid, rows, preds in zip(fold_ids, fold_rows, fold_preds):
        rows = np.asarray(rows, dtype=np.int64)
        preds = np.asarray(preds, dtype=np.float32).ravel()
        if len(rows) != len(preds):
            raise ValueError(f'oof_pack_from_folds: fold {fid} rows '
                             f'({len(rows)}) != preds ({len(preds)})')
        rows_l.append(rows)
        preds_l.append(preds)
        fids_l.append(np.full(len(rows), int(fid), dtype=np.int16))
    rows = np.concatenate(rows_l) if rows_l else np.empty(0, np.int64)
    preds = np.concatenate(preds_l) if preds_l else np.empty(0, np.float32)
    fids = np.concatenate(fids_l) if fids_l else np.empty(0, np.int16)
    all_times_s = np.asarray(all_times_s, dtype=np.int64)
    keep = all_times_s[rows] <= int(holdout_boundary_s)
    rows, preds, fids = rows[keep], preds[keep], fids[keep]
    starts = np.array([ticker_boundaries[t][0] for t in tickers],
                      dtype=np.int64)
    tick_idx = np.searchsorted(starts, rows, side='right') - 1
    return {
        'ticker': np.asarray(tickers, dtype=np.str_)[tick_idx],
        'ts_ns': all_times_s[rows] * 10 ** 9,
        'oof_pred': preds.astype(np.float32),
        'fold_id': fids,
    }


def write_oof_npz(path, pack, saved_at, score) -> None:
    """Atomic tmp+os.replace npz write, fingerprinted to the manifest's
    saved_at + round-4 score. Caller handles exceptions (fail-soft)."""
    tmp = f'{path}.tmp.{os.getpid()}'
    try:
        with open(tmp, 'wb') as f:
            np.savez_compressed(
                f, ticker=pack['ticker'], ts_ns=pack['ts_ns'],
                oof_pred=pack['oof_pred'], fold_id=pack['fold_id'],
                saved_at=np.array(str(saved_at)),
                score=np.array(round(float(score), 4)))
        os.replace(tmp, path)
    finally:
        try:
            os.unlink(tmp)   # no-op after a successful replace
        except OSError:
            pass


def load_oof_npz(path, manifest) -> tuple:
    """(pack, status); status in {'ok','missing','stale','unreadable'}.

    'ok' requires the npz fingerprint (saved_at string-equal, score equal
    within 1e-9 — both sides store round(score, 4)) to match the CURRENT
    champion manifest; anything else is 'stale' and the caller falls back
    loudly to the in-sample path. numpy + stdlib only.
    """
    if not os.path.exists(path):
        return None, 'missing'
    try:
        with np.load(path, allow_pickle=False) as z:
            required = ('ticker', 'ts_ns', 'oof_pred', 'saved_at', 'score')
            if any(k not in z.files for k in required):
                return None, 'unreadable'
            pack = {k: np.asarray(z[k]) for k in
                    ('ticker', 'ts_ns', 'oof_pred', 'fold_id')
                    if k in z.files}
            npz_saved_at = str(z['saved_at'])
            npz_score = float(z['score'])
    except Exception:
        return None, 'unreadable'
    if manifest is None:
        return None, 'stale'
    if npz_saved_at != manifest.get('saved_at'):
        return None, 'stale'
    try:
        if abs(npz_score - float(manifest.get('score'))) > 1e-9:
            return None, 'stale'
    except (TypeError, ValueError):
        return None, 'stale'
    return pack, 'ok'


def join_oof_to_index(index_ns, ticker, pack) -> np.ndarray:
    """Per-row OOF prediction for one ticker's bar index; NaN outside
    coverage (the OOF consumer DROPS those rows — never backfills).
    index_ns is floored to whole seconds before matching: the pack's ts_ns
    are seconds-truncated (load_data's // 10**9). Pure numpy."""
    index_ns = np.asarray(index_ns, dtype=np.int64)
    floored = (index_ns // 10 ** 9) * 10 ** 9
    out = np.full(len(index_ns), np.nan, dtype=np.float64)
    sel = pack['ticker'] == str(ticker)
    ts = np.asarray(pack['ts_ns'][sel], dtype=np.int64)
    if ts.size == 0:
        return out
    vals = np.asarray(pack['oof_pred'][sel], dtype=np.float64)
    order = np.argsort(ts, kind='stable')
    ts_s, vals_s = ts[order], vals[order]
    # Dedupe keeping the LAST occurrence (defensive: fold val slices are
    # time-disjoint by construction, so (ticker, ts) keys are unique).
    keep = np.ones(ts_s.size, dtype=bool)
    keep[:-1] = ts_s[1:] != ts_s[:-1]
    ts_s, vals_s = ts_s[keep], vals_s[keep]
    pos = np.searchsorted(ts_s, floored)
    in_range = pos < ts_s.size
    hit = np.where(in_range)[0]
    hit = hit[ts_s[pos[hit]] == floored[hit]]
    out[hit] = vals_s[pos[hit]]
    return out


def oof_starvation_tier(n_rows) -> tuple:
    """B04.3 binding tiers: ('starved', None) below OOF_MIN_ROWS,
    ('shrunk', param overrides) below OOF_FULL_PARAMS_MIN_ROWS,
    ('full', None) otherwise."""
    n = int(n_rows)
    if n < OOF_MIN_ROWS:
        return 'starved', None
    if n < OOF_FULL_PARAMS_MIN_ROWS:
        return 'shrunk', dict(OOF_SHRUNK_PARAMS,
                              min_data_in_leaf=max(20, n // 20))
    return 'full', None


def _notify(msg: str):
    """Best-effort (shadow.py pattern) — a notify failure never blocks."""
    try:
        from notify import notify
        notify(msg, level='warning', dedupe_key=f'meta-{msg[:40]}')
    except Exception:
        pass


def _write_refusal(paths: dict, reasons: list, extra: dict | None = None):
    """{prefix}meta_refused.json sidecar (tmp+os.replace, never raises) —
    instrumentation for the refusal path; live triple untouched."""
    try:
        tmp = None
        import datetime as _dt
        path = paths.get('refused')
        if path is None:   # test seams build their own dicts without the key
            path = Path(str(paths['meta'])).with_name(
                Path(str(paths['meta'])).name.replace('meta_meta.json',
                                                      'meta_refused.json'))
        payload = {
            'refused_at': _dt.datetime.now(_dt.timezone.utc).isoformat(),
            'reasons': list(reasons),
            **(extra or {}),
        }
        tmp = f'{path}.tmp.{os.getpid()}'
        with open(tmp, 'w') as f:
            json.dump(payload, f, indent=2, default=str)
        os.replace(tmp, path)
    except Exception as e:
        if tmp:
            try:
                os.unlink(tmp)
            except OSError:
                pass
        print(f"[META] refusal sidecar write failed ({e}) — refusal still holds")


def promote_staged_meta(prefix: str = '') -> bool:
    """Guarded, atomic staged->live promotion (D13b). The ONLY path that may
    replace live meta artifacts. Refusal leaves the existing live triple (or
    the fail-open-neutral absence) untouched."""
    import shutil
    paths = _paths(prefix)
    staged = {k: Path(str(paths[k]) + '.staged') for k in ('model', 'calib', 'meta')}
    missing = [k for k in staged if not staged[k].exists()]
    if missing:
        print(f"[META] staged promote REFUSED: missing staged {missing}")
        _notify(f"[META] {prefix or 'crypto'} staged promote refused: "
                f"missing staged {missing}")
        return False
    try:
        with open(staged['meta']) as f:
            payload = json.load(f)
    except Exception as e:
        print(f"[META] staged promote REFUSED: staged meta unreadable ({e})")
        _notify(f"[META] {prefix or 'crypto'} staged promote refused: "
                f"staged meta unreadable")
        return False
    calib_prov = payload.get('calibration') or {}
    if calib_prov.get('publish_guards_ok') is not True:
        print(f"[META] staged promote REFUSED: guards not passed "
              f"({calib_prov.get('guard_reasons')}) — previous live triple "
              f"(or neutral fail-open) retained")
        _notify(f"[META] {prefix or 'crypto'} staged promote refused: "
                f"guards not passed")
        _write_refusal(paths, ['staged_guards_not_ok'],
                       {'calibration': calib_prov})
        return False
    # Primary-pairing freshness: refuse if the champion manifest changed
    # since staging (the staged meta's 'pred' feature belongs to that primary)
    fp = payload.get('primary')
    if fp and fp.get('manifest_mtime_ns') is not None:
        p_pre = f'{prefix}_' if prefix else ''
        mpath = BASE_DIR / f'{p_pre}model_v2.manifest.json'
        try:
            cur = os.stat(mpath).st_mtime_ns
        except OSError:
            cur = None
        if cur != fp['manifest_mtime_ns']:
            print("[META] staged promote REFUSED: primary manifest changed "
                  "since staging — retrain required")
            _notify(f"[META] {prefix or 'crypto'} staged promote refused: "
                    f"primary manifest changed since staging")
            return False
    # .prev backups of the CURRENT live triple (moved here from train_meta —
    # rollback pairs are made at the moment live is replaced)
    for key in ('model', 'calib', 'meta'):
        if paths[key].exists():
            try:
                shutil.copy2(paths[key], str(paths[key]) + '.prev')
            except OSError as e:
                print(f"[META] WARNING: .prev backup failed for "
                      f"{paths[key].name}: {e} — the rollback pair may be "
                      f"incomplete or mismatched")
    # Atomic renames, meta -> calib -> model (existing publish order convention)
    try:
        os.replace(staged['meta'], paths['meta'])
        os.replace(staged['calib'], paths['calib'])
        os.replace(staged['model'], paths['model'])
    except OSError as e:
        print(f"[META] staged promote FAILED mid-rename ({e}) — inspect "
              f"triple consistency")
        _notify(f"[META] {prefix or 'crypto'} staged promote FAILED "
                f"mid-rename — inspect triple consistency")
        return False
    # housekeeping: clear shadow.py's rename-aside stale files, if any
    for key in ('model', 'calib', 'meta'):
        try:
            os.unlink(str(paths[key]) + '.stale')
        except OSError:
            pass
    invalidate_cache()
    print(f"[META] staged artifacts promoted to live: {paths['model'].name}, "
          f"{paths['calib'].name}, {paths['meta'].name}")
    return True


